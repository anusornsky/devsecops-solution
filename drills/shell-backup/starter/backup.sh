#!/usr/bin/env bash
# โจทย์บันได Linux ขั้น ③ · ร่างของ AI ที่ "รันแล้วได้ไฟล์" แต่ผิด 3 อย่างเมื่อมีอะไรพัง
# ใช้: ./backup.sh <โฟลเดอร์ปลายทาง> <ต้นทาง1> [ต้นทาง2 ...]   → ได้ <ปลายทาง>/backup-<วันเวลา>.tgz เก็บ 3 ไฟล์ล่าสุด
# งานของคุณ: แก้ให้ ./check.sh ./backup.sh ผ่าน
#   1. ต้นทางหาย/อ่านไม่ได้ → exit ไม่เป็น 0 และไม่พิมพ์ว่าสำเร็จ
#   2. ล้มกลางทาง → ไม่มีไฟล์ backup ครึ่งๆ ค้าง (ทั้ง .tgz และไฟล์ชั่วคราว)
#   3. ลบของเก่าเหลือ 3 ไฟล์ล่าสุด โดยไม่ลบไฟล์ backup ที่ดีทิ้งเพราะรอบที่ล้ม
dest=$1
shift
tar czf "$dest/backup-$(date +%Y%m%d-%H%M%S).tgz" "$@"
ls -t $dest/*.tgz | tail -n +4 | xargs rm
echo "backup ok"
